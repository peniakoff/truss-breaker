import type { CalculationResult } from '@/domain/models'
import { paToMpa } from '@/domain/physics/units'
import { CANVAS_WIDTH, CANVAS_HEIGHT } from '@/utils/constants'

const STYLE_PROPS = ['fill', 'stroke', 'stroke-width', 'stroke-dasharray', 'opacity', 'font-size', 'font-weight', 'font-family'] as const

function inlineSvgStyles(clone: SVGSVGElement, source: SVGSVGElement): void {
  const sourceEls = [source, ...Array.from(source.querySelectorAll('*'))]
  const cloneEls = [clone, ...Array.from(clone.querySelectorAll('*'))]

  for (let i = 0; i < sourceEls.length; i++) {
    const src = sourceEls[i] as SVGElement
    const dst = cloneEls[i] as SVGElement
    if (!dst) continue
    const computed = window.getComputedStyle(src)
    for (const prop of STYLE_PROPS) {
      const value = computed.getPropertyValue(prop)
      if (value && value !== 'none' && value !== 'normal') {
        dst.setAttribute(prop, value)
      }
    }
  }
}

async function svgToPngDataUrl(svgElement: SVGSVGElement): Promise<string> {
  const clone = svgElement.cloneNode(true) as SVGSVGElement
  inlineSvgStyles(clone, svgElement)

  clone.setAttribute('viewBox', `0 0 ${CANVAS_WIDTH} ${CANVAS_HEIGHT}`)
  clone.setAttribute('width', String(CANVAS_WIDTH))
  clone.setAttribute('height', String(CANVAS_HEIGHT))

  const serializer = new XMLSerializer()
  const svgString = serializer.serializeToString(clone)
  const svgBlob = new Blob([svgString], { type: 'image/svg+xml;charset=utf-8' })
  const url = URL.createObjectURL(svgBlob)

  return new Promise((resolve, reject) => {
    const img = new Image()
    img.onload = () => {
      const canvas = document.createElement('canvas')
      const scale = 0.25
      canvas.width = CANVAS_WIDTH * scale
      canvas.height = CANVAS_HEIGHT * scale
      const ctx = canvas.getContext('2d')
      if (!ctx) {
        URL.revokeObjectURL(url)
        reject(new Error('Canvas context unavailable'))
        return
      }
      ctx.fillStyle = '#ffffff'
      ctx.fillRect(0, 0, canvas.width, canvas.height)
      ctx.drawImage(img, 0, 0, canvas.width, canvas.height)
      URL.revokeObjectURL(url)
      resolve(canvas.toDataURL('image/png'))
    }
    img.onerror = () => {
      URL.revokeObjectURL(url)
      reject(new Error('Failed to render SVG'))
    }
    img.src = url
  })
}

export interface PdfReportInput {
  projectName: string
  results: CalculationResult
  svgElement: SVGSVGElement
}

export interface PdfReportResult {
  diagramRendered: boolean
}

export async function generatePdfReport(input: PdfReportInput): Promise<PdfReportResult> {
  const { jsPDF } = await import('jspdf')

  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' })
  const pageWidth = doc.internal.pageSize.getWidth()
  const pageHeight = doc.internal.pageSize.getHeight()
  let y = 15
  let diagramRendered = false

  doc.setFontSize(16)
  doc.text('Truss Breaker — Calculation Report', pageWidth / 2, y, { align: 'center' })
  y += 8

  doc.setFontSize(10)
  doc.text(`Project: ${input.projectName}`, 14, y)
  y += 5
  doc.text(`Date: ${new Date().toLocaleString()}`, 14, y)
  y += 8

  try {
    const pngDataUrl = await svgToPngDataUrl(input.svgElement)
    const imgWidth = pageWidth - 28
    const imgHeight = imgWidth * (CANVAS_HEIGHT / CANVAS_WIDTH)
    doc.addImage(pngDataUrl, 'PNG', 14, y, imgWidth, imgHeight)
    y += imgHeight + 10
    diagramRendered = true
  } catch {
    doc.setTextColor(200, 0, 0)
    doc.text('(Structure diagram could not be rendered)', 14, y)
    doc.setTextColor(0, 0, 0)
    y += 10
  }

  y = drawTable(doc, pageWidth, pageHeight, 14, y, 'Axial Forces', ['Element', 'Force [kN]', 'Stress [MPa]'],
    input.results.elementResults.map((er) => [
      er.elementId,
      er.axialForce.toFixed(2),
      paToMpa(er.stress).toFixed(1),
    ]),
  )

  y += 4
  y = drawTable(doc, pageWidth, pageHeight, 14, y, 'Support Reactions', ['Node', 'RX [kN]', 'RY [kN]'],
    input.results.reactions.map((r) => [
      r.nodeId,
      r.forceX.toFixed(2),
      r.forceY.toFixed(2),
    ]),
  )

  y += 4
  drawTable(doc, pageWidth, pageHeight, 14, y, 'Displacements', ['Node', 'dx [mm]', 'dy [mm]'],
    input.results.displacements.map((d) => [
      d.nodeId,
      (d.dx * 1000).toFixed(4),
      (d.dy * 1000).toFixed(4),
    ]),
  )

  const pageCount = doc.getNumberOfPages()
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i)
    doc.setFontSize(8)
    doc.text(
      'Generated by Truss Breaker',
      pageWidth / 2,
      pageHeight - 8,
      { align: 'center' },
    )
  }

  const safeName = input.projectName.replace(/[^a-zA-Z0-9_-]/g, '_') || 'truss'
  doc.save(`${safeName}-report.pdf`)
  return { diagramRendered }
}

function drawTable(
  doc: import('jspdf').jsPDF,
  pageWidth: number,
  pageHeight: number,
  x: number,
  startY: number,
  title: string,
  headers: string[],
  rows: string[][],
): number {
  const colWidth = (pageWidth - 28) / headers.length
  const rowHeight = 5
  const bottomMargin = 20
  let y = startY

  function ensureSpace(needed: number): void {
    if (y + needed > pageHeight - bottomMargin) {
      doc.addPage()
      y = 15
    }
  }

  function drawHeaderRow(): void {
    doc.setFontSize(9)
    headers.forEach((header, i) => {
      doc.text(header, x + i * colWidth, y)
    })
    y += rowHeight
  }

  ensureSpace(12)
  doc.setFontSize(12)
  doc.text(title, x, y)
  y += 6
  drawHeaderRow()

  for (const row of rows) {
    ensureSpace(rowHeight + 2)
    row.forEach((cell, i) => {
      doc.text(cell, x + i * colWidth, y)
    })
    y += rowHeight
  }

  return y
}
