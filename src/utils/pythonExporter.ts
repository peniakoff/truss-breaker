import type { TrussData, TrussNode } from '@/domain/models'
import { SupportType } from '@/domain/models'
import { GRID_SIZE } from '@/utils/constants'

/** Canvas Y is down; anastruct uses Y up — flip vertical axis. */
export function toAnastructCoords(node: TrussNode): { x: number; y: number } {
  return {
    x: node.x / GRID_SIZE,
    y: -(node.y / GRID_SIZE),
  }
}

function formatCoord(value: number): string {
  return value.toFixed(4)
}

function supportCode(type: SupportType, x: string, y: string): string {
  const lookup = `find_node_id(${x}, ${y})`
  switch (type) {
    case SupportType.FIXED:
      return `ss.add_support_fixed(${lookup})`
    case SupportType.ROLLER_X:
      return `ss.add_support_roll(${lookup}, direction='x')`
    case SupportType.ROLLER_Y:
      return `ss.add_support_roll(${lookup}, direction='y')`
    default: {
      const _exhaustive: never = type
      return `# Unknown support type: ${_exhaustive}`
    }
  }
}

export function generatePythonScript(data: TrussData, projectName = 'truss'): string {
  const { nodes, elements, materials, supports, loads } = data

  const lines: string[] = [
    '# Generated by Truss Breaker',
    `# Project: ${projectName.replace(/[\r\n]/g, ' ')}`,
    '#',
    '# Units: meters (m), Newtons (N), Pascals (Pa)',
    '# Coordinates: anastruct Y-up (canvas Y is flipped: y_ana = -y_canvas)',
    '# Loads: Fy is negated to match the Y-axis flip',
    '#',
    '# pip install anastruct matplotlib',
    '',
    'from anastruct import SystemElements',
    '',
    'ss = SystemElements(EA_create=True)',
    '',
    'def find_node_id(x, y, tol=1e-4):',
    '    """Find anastruct node ID by coordinates (assigned on element creation)."""',
    '    for node_id, node in ss.node_map.items():',
    '        vx, vy = node.vertex[0], node.vertex[1]',
    '        if abs(vx - x) < tol and abs(vy - y) < tol:',
    '            return node_id',
    "    raise ValueError(f'No anastruct node at ({x}, {y})')",
    '',
    '# --- Elements ---',
  ]

  for (const element of elements) {
    const start = nodes.find((n) => n.id === element.startNodeId)
    const end = nodes.find((n) => n.id === element.endNodeId)
    const material = materials.find((m) => m.id === element.materialId)
    if (!start || !end || !material) continue

    const EA = material.youngModulus * element.crossSection.area
    const s = toAnastructCoords(start)
    const e = toAnastructCoords(end)

    lines.push(
      `ss.add_truss_element([[${formatCoord(s.x)}, ${formatCoord(s.y)}], [${formatCoord(e.x)}, ${formatCoord(e.y)}]], EA=${EA.toExponential(4)})  # ${element.id}`,
    )
  }

  lines.push('', '# --- Supports ---')
  for (const support of supports) {
    const node = nodes.find((n) => n.id === support.nodeId)
    if (!node) continue
    const { x, y } = toAnastructCoords(node)
    lines.push(`${supportCode(support.type, formatCoord(x), formatCoord(y))}  # ${support.nodeId}`)
  }

  lines.push('', '# --- Loads (kN → N, Fy flipped for Y-up) ---')
  for (const load of loads) {
    const node = nodes.find((n) => n.id === load.nodeId)
    if (!node) continue
    const { x, y } = toAnastructCoords(node)
    const fx = (load.forceX * 1000).toFixed(1)
    const fy = (-load.forceY * 1000).toFixed(1)
    lines.push(
      `ss.point_load(find_node_id(${formatCoord(x)}, ${formatCoord(y)}), Fx=${fx}, Fy=${fy})  # ${load.nodeId}`,
    )
  }

  lines.push(
    '',
    '# --- Solve & visualize ---',
    'ss.solve()',
    'ss.show_structure()',
    'ss.show_reaction_force()',
    'ss.show_axial_force()',
    '',
    '# Print nodal displacements (anastruct 2D: ux, uz)',
    'for node_id, node in ss.node_map.items():',
    '    print(f"Node {node_id}: ux={node.ux:.6e} m, uz={node.uz:.6e} m")',
    '',
  )

  return lines.join('\n')
}

export function downloadPythonScript(content: string, filename: string): void {
  const blob = new Blob([content], { type: 'text/x-python' })
  const url = URL.createObjectURL(blob)
  const anchor = document.createElement('a')
  anchor.href = url
  anchor.download = filename
  anchor.click()
  URL.revokeObjectURL(url)
}
